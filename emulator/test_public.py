# First run end to end, as a new user would do it, against the fake printer: the one-time setup link, the setup page
# (printer, PIN, cameras, template, watcher), then the phone page, a sliced file sent to the printer, pause and cancel.
# Run: python -I emulator/test_public.py [--port 8771] [--printer-ip 127.0.0.3] [--template <Flash Studio export .3mf>]
# Starts its own sim hub + fake printer and stops them after. Needs nothing but Python: no printer, no Flash Studio,
# no Claude. With --template it also checks that a real Flash Studio export is taken as the template.
import argparse, http.client, json, os, shutil, subprocess, sys, time, urllib.error, urllib.parse, urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
SIM = os.path.join(HERE, "sim-hub")
FAKE = ""
PRINTER_IP = ""
results = []
BASE = ""
JAR = ""  # the cookies this "browser" holds


def check(name, ok, detail=""):
    results.append(bool(ok))
    print(("PASS " if ok else "FAIL ") + name + (f"  ({detail})" if detail and not ok else ""), flush=True)


def call(path, data=None, raw=False, key=None, cookie=None, base=None, ctype="application/json"):
    body = data if isinstance(data, (bytes, type(None))) else json.dumps(data).encode()
    head = {"Content-Type": ctype}
    if key:
        head["X-Hub-Key"] = key
    cookie = JAR if cookie is None else cookie
    if cookie:
        head["Cookie"] = cookie
    req = urllib.request.Request((base or BASE) + path, data=body, headers=head)
    try:
        with urllib.request.urlopen(req, timeout=40) as r:
            code, out, hdr = r.status, r.read(), r.headers
    except urllib.error.HTTPError as e:
        code, out, hdr = e.code, e.read(), e.headers
    if raw:
        return code, out, hdr
    try:
        return code, json.loads(out)
    except ValueError:
        return code, out


def add_cookie(hdr):
    """Keep what Set-Cookie gave, like a browser (name=value only)."""
    global JAR
    jar = dict(c.split("=", 1) for c in JAR.split("; ") if "=" in c)
    for sc in hdr.get_all("Set-Cookie") or []:
        k, _, v = sc.split(";")[0].partition("=")
        if v:
            jar[k] = v
        else:
            jar.pop(k, None)
    JAR = "; ".join(f"{k}={v}" for k, v in jar.items())


def gcode(layers=20, extra=()):
    """A small plain G-code file in the shape Flash Studio writes (header, layer markers, moves)."""
    out = ["; HEADER_BLOCK_START", "; generated by test_public on 2026-01-01 at 00:00:00", f"; total layer number: {layers}",
           "; HEADER_BLOCK_END", "; filament used [g] = 1.20,0,0,0", "; total filament used [g] = 1.20",
           "; estimated printing time (normal mode) = 4m 0s", "; filament_type = PLA;PLA;PLA;PLA",
           "; filament_colour = #FFFFFF;#1E5BD8;#F5D000;#FF69B4", "; nozzle_temperature = 210,210,210,210",
           "M140 S55", "M104 S210", "M190 S55", "M109 S210", "T0", "G28", "G90", "M83", *extra]
    for n in range(layers):
        z = 0.2 * (n + 1)
        out += [";LAYER_CHANGE", f";Z:{z:.1f}", ";HEIGHT:0.2", f"G1 Z{z:.1f} F600", "G1 X100 Y100 F9000"]
        out += [f"G1 X{x} Y{y} E0.5 F3000" for x, y in ((140, 100), (140, 140), (100, 140), (100, 100))]
    out += ["M104 S0", "M140 S0"]
    return ("\n".join(out) + "\n").encode()


def wait(cond, timeout=30, key=None):
    end, s = time.time() + timeout, {}
    while time.time() < end:
        code, r = call("/api/status", key=key)
        s = r.get("printer", {}) if isinstance(r, dict) else {}
        if cond(s):
            return s
        time.sleep(1)
    return s


def main(template):
    # --- before setup: only the one-time link opens the setup page ---
    code, page, _ = call("/", raw=True)
    check("first run without the setup link: 'not set up' page only", code == 200 and b"not set up yet" in page
          and b"setup-url.txt" in page, page[:80])
    for _ in range(20):
        if os.path.exists(os.path.join(SIM, "setup-url.txt")):
            break
        time.sleep(0.5)
    link = open(os.path.join(SIM, "setup-url.txt")).read().strip()
    check("setup link written for setup.ps1", "/setup?token=" in link, link)
    u = urllib.parse.urlparse(BASE)
    c = http.client.HTTPConnection(u.hostname, u.port, timeout=10)
    c.request("GET", "/setup?token=wrong")
    r = c.getresponse()
    r.read()
    check("a wrong setup token is refused", r.status == 403, r.status)
    c.request("GET", urllib.parse.urlparse(link).path + "?" + urllib.parse.urlparse(link).query)
    r = c.getresponse()
    r.read()
    add_cookie(r.headers)
    c.close()
    check("setup link swaps the token for a cookie", r.status == 303 and "hubsetup=" in JAR, (r.status, JAR))
    code, page, _ = call("/", raw=True)
    check("first run opens the setup page with the link's cookie", code == 200 and b"C5 Print Hub setup" in page, page[:80])
    code, st = call("/api/setup")
    check("setup state reads, not done yet", code == 200 and st.get("setup_done") is False, str(st)[:200])
    code, r = call("/api/setup", cookie="")
    check("setup API refused without the link's cookie", code == 401, code)
    code, r = call("/api/status")
    check("phone API locked before setup", code == 401, code)

    code, r = call("/api/setup/printer", {"ip": PRINTER_IP, "serial": "SIMULATOR0001", "check_code": "wrong"})
    check("wrong check code: plain error", code == 400 and "check code" in r.get("error", "").lower(), r)
    code, r = call("/api/setup/printer", {"ip": "not an ip", "serial": "x", "check_code": "y"})
    check("bad address refused", code == 400, r)
    code, r = call("/api/setup/printer", {"ip": "8.8.8.8", "serial": "x", "check_code": "y"})
    check("printer address on the internet refused", code == 400 and "own network" in r.get("error", ""), r)
    code, r = call("/api/setup/printer", {"ip": PRINTER_IP, "serial": "SIMULATOR0001", "check_code": "simcheck"})
    check("printer connects with serial + check code", code == 200 and r.get("ok"), r)

    code, r = call("/api/setup/done", {})
    check("cannot finish without a PIN", code == 400, r)
    code, r = call("/api/setup/pin", {"pin": "12"})
    check("short PIN refused", code == 400, r)
    code, r, hdr = call("/api/setup/pin", {"pin": "2468"}, raw=True)
    add_cookie(hdr)
    check("PIN saved, browser logged in", code == 200 and "hub=" in JAR, r)
    cookie = [x for x in JAR.split("; ") if x.startswith("hub=")][0]

    code, img, _ = call("/api/setup/camera.jpg?which=printer", raw=True)
    check("printer camera preview", code == 200 and img[:2] == b"\xff\xd8", f"HTTP {code}")
    code, r = call("/api/setup/camera", {"url": "http://8.8.8.8:8080"})
    check("camera address off the home network refused", code == 400 and "home network" in r.get("error", ""), r)
    code, r = call("/api/setup/camera", {"url": "http://127.0.0.1:9"})
    check("dead phone camera: plain error", code == 400 and "no picture" in r.get("error", ""), r)
    code, r = call("/api/setup/camera", {"url": ""})
    check("no phone camera is fine", code == 200 and r.get("ok"), r)

    code, r = call("/api/setup/template/latest")
    check("look for Flash Studio slices answers", code == 200 and "files" in r, r)
    code, r = call("/api/setup/template/upload", b"not a 3mf", ctype="application/octet-stream")
    check("a non-3MF is refused as template", code == 400 and "template" in r.get("error", ""), r)
    if template:
        code, r = call("/api/setup/template/upload?only_these_presets=1", open(template, "rb").read(),
                       ctype="application/octet-stream")
        check("your Flash Studio export becomes the template", code == 200 and len(r.get("filaments") or []) == 4, r)
        code, st = call("/api/setup")
        check("template shows on the setup page", (st.get("template") or {}).get("problems") == [], st.get("template"))

    code, r = call("/api/setup/watcher", {"backend": "api", "api_key": ""})
    check("API watcher without a key refused", code == 400, r)
    code, r = call("/api/setup/watcher", {"backend": "api", "api_key": "abc"})
    check("not an Anthropic key refused", code == 400, r)
    # OpenAI-compatible backend (experimental) against the local mock server, and the Test button for it
    sys.path.insert(0, HERE)
    import mock_openai
    srv, murl = mock_openai.start()
    oa = lambda model, **k: call("/api/setup/watcher", dict({"backend": "openai", "preset": "custom", "base_url": murl,
                                                             "model": model, "openai_key": "local-test-key",
                                                             "local_server": True}, **k))
    code, r = oa("")
    check("OpenAI-compatible without a model refused", code == 400 and "model" in r.get("error", ""), r)
    code, r = oa("good", base_url="not a url")
    check("OpenAI-compatible bad address refused", code == 400, r)
    code, r = oa("good", local_server=False)
    check("plain http needs the 'my own local server' tick", code == 400 and "local server" in r.get("error", ""), r)
    code, r = oa("good")
    check("OpenAI-compatible backend saved", code == 200 and r.get("backend") == "openai"
          and r["openai"]["model"] == "good" and r["openai"]["key_end"] == "-key", r)
    code, raw, _ = call("/api/setup", raw=True)
    check("setup page never shows the saved key", b"local-test-key" not in raw)
    code, v = call("/api/setup/watcher/test", {})
    check("Test button: good verdict", code == 200 and v.get("verdict") == "ok", v)
    check("Test sent the real camera frame", mock_openai.LAST["body"]["messages"][1]["content"][0]["image_url"]["url"]
          .startswith("data:image/jpeg;base64,/9j/"), str(mock_openai.LAST.get("body"))[:120])
    oa("noimage")
    code, v = call("/api/setup/watcher/test", {})
    check("Test button: model without images gives a plain error", v.get("verdict") == "error"
          and "does not take images" in v.get("reason", ""), v)
    oa("garbled")
    code, v = call("/api/setup/watcher/test", {})
    check("Test button: garbled answer shows as unsure", v.get("verdict") == "unsure", v)
    oa("http500")
    code, v = call("/api/setup/watcher/test", {})
    check("Test button: server error shows as unreachable", v.get("verdict") == "error"
          and v.get("reason", "").startswith("unreachable"), v)
    srv.shutdown()

    code, r = call("/api/setup/watcher", {"backend": "", "enabled": True})
    check("watcher stays off with no backend", code == 200 and r.get("enabled") is False and r.get("backend") == "", r)

    code, r, hdr = call("/api/setup/done", {}, raw=True)
    check("setup done", code == 200, r)
    check("setup link removed once setup is done", not os.path.exists(os.path.join(SIM, "setup-url.txt")))

    # --- after setup ---
    code, page, _ = call("/", raw=True, cookie="")
    check("after setup the page asks for the PIN", code == 200 and b'data-mode="lan"' in page, page[:80])
    code, page, _ = call("/setup", raw=True, cookie="")
    check("setup page now needs the PIN", code == 200 and b'data-mode="lan"' in page, page[:80])
    code, r = call("/api/setup", cookie="")
    check("setup API now needs the PIN", code == 401, code)
    hs = [x for x in JAR.split("; ") if x.startswith("hubsetup=")]
    code, r = call("/api/setup", cookie=hs[0] if hs else "hubsetup=x")
    check("the setup link's cookie stops working after setup", code == 401, code)
    code, r = call("/login", {"password": "2468"}, cookie="")
    check("login with the new PIN", code == 200 and r.get("ok"), r)
    code, page, _ = call("/", raw=True, cookie=cookie)
    check("main page loads", code == 200 and b"<title>C5 Print Hub</title>" in page and b"+ New print" in page, page[:80])
    code, page, _ = call("/setup", raw=True, cookie=cookie)
    check("setup page reopens after login", code == 200 and b"C5 Print Hub setup" in page)
    for path in ("/static/viewer3d.js", "/static/vendor/three-0.169.0/three.module.min.js", "/manifest.json"):
        code, body, _ = call(path, raw=True, cookie=cookie)
        check(f"serves {path}", code == 200 and len(body) > 100, f"HTTP {code}")
    code, man, _ = call("/manifest.json", raw=True)
    check("app name in the manifest", b"C5 Print Hub" in man)

    sys.path.insert(1, os.path.dirname(HERE))
    import security
    disk = json.load(open(os.path.join(SIM, "config.json")))
    key = security.cfg_from_disk(dict(disk))["api_token"]
    check("api_token encrypted in config.json on Windows", os.name != "nt" or (disk["api_token"].startswith("dpapi:")
          and key not in json.dumps(disk)), disk["api_token"][:12])
    code, r = call("/api/status", key="2468", cookie="")
    check("the PIN is not an API key", code == 401, code)
    s = wait(lambda s: s.get("online"), key=key)
    check("phone page status: printer online", s.get("online") and s.get("status") == "ready", s)
    code, r = call("/api/status", key=key)
    check("watcher shown as not set up", r.get("watch_ready") is False and r["watch"]["enabled"] is False, r.get("watch"))
    code, r = call("/api/watch", {"enabled": True}, key=key)
    check("turning on an unset watcher says how to set it up", code == 400 and "Setup" in r.get("error", ""), r)

    call("/sim/load?slot=1&colour=%23FFFFFF&material=PLA", base=FAKE)
    code, job = call("/api/upload?name=test-square.gcode", gcode(), key=key, ctype="application/octet-stream")
    check("sliced G-code uploads", code == 200 and job.get("kind") == "sliced", job)
    jid = job.get("id")
    check("a file not sliced by Flash Studio is flagged", job.get("check", {}).get("passed") is False, job.get("check"))
    code, r = call(f"/api/jobs/{jid}/print", {"plate_clear": True}, key=key)
    check("flagged file is not sent without Send anyway", code == 400, r)
    code, r = call(f"/api/jobs/{jid}/print", {"plate_clear": False, "allow_unchecked": True}, key=key)
    check("send needs the plate-clear tick", code == 400 and "plate" in r.get("error", ""), r)
    code, r = call(f"/api/jobs/{jid}/print", {"plate_clear": True, "allow_unchecked": True, "leveling": False}, key=key)
    check("Send anyway sends it", code == 200 and r.get("state") == "sent", r)
    s = wait(lambda s: (s.get("status") or "") == "printing", 30, key=key)
    check("printer prints it", s.get("status") == "printing", s.get("status"))
    code, r = call("/api/control", {"action": "pause"}, key=key)
    s = wait(lambda s: (s.get("status") or "") in ("pause", "paused"), 20, key=key)
    check("pause from the phone", code == 200 and s.get("status") in ("pause", "paused"), s.get("status"))
    code, r = call("/api/control", {"action": "cancel"}, key=key)
    s = wait(lambda s: (s.get("status") or "") == "cancel", 20, key=key)
    check("cancel from the phone", code == 200 and s.get("status") == "cancel", s.get("status"))

    code, r = call("/api/drying", {"action": "unlock", "i_checked": True}, key=key)
    check("drying unlock refused when nothing is locked", code == 400, r)

    print(f"\n{sum(results)}/{len(results)} passed", flush=True)
    return 0 if all(results) else 1


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--port", type=int, default=8771)
    ap.add_argument("--printer-ip", default="127.0.0.3", help="loopback address for the fake printer")
    ap.add_argument("--template", help="a Flash Studio export (.3mf) to try as the template")
    a = ap.parse_args()
    BASE, PRINTER_IP, FAKE = f"http://127.0.0.1:{a.port}", a.printer_ip, f"http://{a.printer_ip}:8898"
    for d in ("jobs", "template", "drying", "watch"):
        shutil.rmtree(os.path.join(SIM, d), ignore_errors=True)
    for f in ("config.json", "hub.log", "sessions.json", "setup-url.txt"):
        if os.path.exists(os.path.join(SIM, f)):
            os.remove(os.path.join(SIM, f))
    hub = subprocess.Popen([sys.executable, "-I", os.path.join(HERE, "sim_hub.py"), "--port", str(a.port), "--fresh",
                            "--speed", "20", "--printer-ip", a.printer_ip], stdout=subprocess.DEVNULL,
                           stderr=subprocess.STDOUT)
    rc = 1
    try:
        for _ in range(60):
            try:
                urllib.request.urlopen(BASE + "/manifest.json", timeout=2).read()
                break
            except Exception:
                time.sleep(0.5)
        rc = main(a.template)
    finally:
        subprocess.run(["taskkill", "/F", "/T", "/PID", str(hub.pid)], capture_output=True)  # sim hub + fake printer
    sys.exit(rc)
